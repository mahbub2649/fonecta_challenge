#!/usr/bin/env python3
"""Write docs/final_messages.md: the exact customer messages, produced by the real engine and templates.

    python3 tools/export_messages.py
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from connect import messages  # noqa: E402
from connect.engine import Engine  # noqa: E402

LINK = "https://connect.example/o/abc123"
LISTINGS = [{"name": "Google (Search & Maps)", "seconds": 120}, {"name": "Finder.fi / Fonecta.fi", "seconds": 600},
            {"name": "Bing", "seconds": 86400}, {"name": "Apple Maps", "seconds": 172800}]
OFFERS = [("FI-D0001", "fi", "Finnish, Kahvila Aurora"), ("SE-D0008", "sv", "Swedish, Kafé Linnea (email, so it has a subject line)"),
          ("NO-D0009", "nb", "Norwegian, Bakeri Fjord"), ("FI-D0001", "en", "English, Kahvila Aurora"),
          ("FI-D0017", "fi", "No history, Kahvila Kipinä: asked, not stated"), ("FI-D0004", "fi", "Shopping centre, Muoti Lyhty")]


def batch(engine, eid):
    suggestions = sorted((d for d in engine.decisions_for(eid) if d.action == "SUGGEST"), key=lambda d: d.date)
    items = []
    for d in suggestions:
        if items and (d.to_dict()["date"] > "2026-12-27"):
            break
        items.append({**d.to_dict(), "proposed": d.hours, "final_hours": d.hours})
    return items


def main() -> None:
    engine = Engine()
    out = ["# Final customer messages", "",
           "Generated by `tools/export_messages.py` from the real templates and data. The link is a placeholder.", ""]

    def block(title, body):
        out.extend([f"### {title}", "", "```text", body, "```", ""])

    out.extend(["## First message", ""])
    for eid, lang, title in OFFERS:
        contact = engine.contacts[eid]
        no_history = not any(key[0] == eid for key in engine.history)
        block(title, messages.offer(contact["contact_first_name"], engine.entities[eid]["name"], batch(engine, eid), LINK, lang,
                                    contact["preferred_channel"], no_history))

    aurora = batch(engine, "FI-D0001")
    edited = [{**aurora[0], "final_hours": "07:30-14:00"}, aurora[1]]
    for lang, name in (("fi", "Finnish"), ("sv", "Swedish"), ("nb", "Norwegian"), ("en", "English")):
        out.extend([f"## Follow-ups: {name}", ""])
        block("After approving", messages.confirmation("Aleksi", "Kahvila Aurora", aurora, LISTINGS, lang, LINK))
        block("After editing (Christmas Eve changed to close at 14)", messages.confirmation("Aleksi", "Kahvila Aurora", edited, LISTINGS, lang))
        block("After declining", messages.declined("Aleksi", lang))
        block("Standing permission: applied, then informed", messages.auto_applied("Laura", "Tilitoimisto Otso", aurora, LISTINGS, LINK, lang))
        block("After undoing", messages.undone("Aleksi", aurora[0], lang))
        block("The one reminder", messages.reminder("Aleksi", "Kahvila Aurora", aurora, LINK, lang))
        block("If the write fails", messages.write_failed(lang))
    path = ROOT / "docs" / "final_messages.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
